export function translate(locale: Locale, key: TranslationKey): string {
  return (locale === "es" ? es[key] : undefined) ?? en[key];
}
// Translate only known interface copy. Unknown server errors retain their original detail.
// Never call this on user-authored letters, names, addresses or filenames.
export function translateMessage(locale: Locale, message: string): string {
  if (locale === "en") return message;
  if (Object.prototype.hasOwnProperty.call(en, message)) return translate(locale, message as TranslationKey);
  const deadlines = [
    ["Preparation ends: ", "Preparation ends: {date}"],
    ["Recovery ends: ", "Recovery ends: {date}"],
    ["Recovery ended: ", "Recovery ended: {date}"],
  ] as const;
  for (const [prefix, key] of deadlines) {
    if (message.startsWith(prefix)) return formatTranslation(locale, key, { date: message.slice(prefix.length) });
  }
  if (message.startsWith("Deletion blocked. ")) {
    return formatTranslation(locale, "Deletion blocked. {detail}", { detail: translateMessage(locale, message.slice(18)) });
  }
  const asset = /^(Letter|Voice|Video|Photo|Document)( \d+)?$/.exec(message);
  if (asset) return translateMessage(locale, asset[1]) + (asset[2] ?? "");
  // The loader combines only fixed asset labels and fixed error descriptions.
  const issues = message.split(/ (?=(?:Letter|Voice|Video|Photo|Document)(?: \d+)?: )/);
  if (issues.every(issue => /^(Letter|Voice|Video|Photo|Document)( \d+)?: /.test(issue))) {
    return issues.map(issue => {
      const separator = issue.indexOf(": ");
      return translateMessage(locale, issue.slice(0, separator)) + ": " + translateMessage(locale, issue.slice(separator + 2));
    }).join(" ");
  }
  return message;
}

export function formatTranslation(locale: Locale, key: TranslationKey, values: Record<string, string | number>): string {
  // One pass: inserted user values are never translated or treated as templates.
  return translate(locale, key).replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder);
}
